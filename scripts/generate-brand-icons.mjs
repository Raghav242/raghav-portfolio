/**
 * Reads every `slug` used in src/data/content.js and writes a trimmed brand-icon
 * module containing only those logos. Keeps the bundle small — the full
 * simple-icons package is a devDependency and never ships to the browser.
 *
 * Run with: npm run icons
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import * as si from 'simple-icons'
import { skills } from '../src/data/content.js'

const outFile = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/brandIcons.js')

const slugs = [
  ...new Set(skills.flatMap((g) => g.items.map((i) => i.slug)).filter(Boolean)),
].sort()

const toRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16))
const toHex = (rgb) =>
  rgb.map((c) => Math.round(Math.min(255, Math.max(0, c))).toString(16).padStart(2, '0')).join('')

/** Relative luminance, WCAG formula. */
function luminance(rgb) {
  const [r, g, b] = rgb.map((c) => {
    const s = c / 255
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

/**
 * Brand palettes assume the logo sits on its own background. Ours sit on a page,
 * so pale marks (JavaScript yellow) get darkened for the light theme and near-black
 * marks (Next.js, GitHub, Express) get lifted for the dark theme.
 */
function forLightTheme(hex) {
  let rgb = toRgb(hex)
  for (let i = 0; i < 6 && luminance(rgb) > 0.55; i += 1) rgb = rgb.map((c) => c * 0.82)
  return toHex(rgb)
}

function forDarkTheme(hex) {
  const rgb = toRgb(hex)
  if (luminance(rgb) > 0.16) return hex
  return toHex(rgb.map((c) => c + (255 - c) * 0.88))
}

const entries = []
const missing = []

for (const slug of slugs) {
  const icon = si['si' + slug.charAt(0).toUpperCase() + slug.slice(1)]
  if (!icon) {
    missing.push(slug)
    continue
  }
  entries.push(
    `  ${JSON.stringify(slug)}: {\n` +
      `    title: ${JSON.stringify(icon.title)},\n` +
      `    hex: ${JSON.stringify(forLightTheme(icon.hex))},\n` +
      `    darkHex: ${JSON.stringify(forDarkTheme(icon.hex))},\n` +
      `    path: ${JSON.stringify(icon.path)},\n` +
      `  },`,
  )
}

const banner = `// AUTO-GENERATED by scripts/generate-brand-icons.mjs — do not edit by hand.
// Regenerate with: npm run icons
// Logos from Simple Icons (https://simpleicons.org), CC0 1.0 Universal.
`

writeFileSync(outFile, `${banner}\nexport const brandIcons = {\n${entries.join('\n')}\n}\n`)

console.log(`Wrote ${entries.length} icons to src/data/brandIcons.js`)
if (missing.length) {
  console.warn(
    `No logo available for: ${missing.join(', ')} — these fall back to monogram tiles.`,
  )
}
